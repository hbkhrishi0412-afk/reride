const resources = {
  en: { translation: en as unknown as Record<string, string> },
};

const LOCALE_LOADERS: Record<string, () => Promise<{ default: Record<string, string> }>> = {
  hi: () => import('./locales/hi'),
  te: () => import('./locales/te'),
  ta: () => import('./locales/ta'),
};

const loadedLocales = new Set<string>(['en']);
let localeLoadQueue: Promise<void> = Promise.resolve();

/** Load a non-English locale chunk once, then register it with i18next. */
export function ensureLocaleLoaded(lng: string): Promise<void> {
  const code = (lng || 'en').split('-')[0].toLowerCase();
  if (!code || code === 'en' || loadedLocales.has(code)) return Promise.resolve();
  const loader = LOCALE_LOADERS[code];
  if (!loader) return Promise.resolve();

  localeLoadQueue = localeLoadQueue.then(async () => {
    if (loadedLocales.has(code)) return;
    try {
      const mod = await loader();
      if (!i18n.hasResourceBundle(code, 'translation')) {
        i18n.addResourceBundle(code, 'translation', mod.default, true, true);
      }
      loadedLocales.add(code);
    } catch (err) {
      console.warn('[i18n] Failed to load locale', code, err);
    }
  });
  return localeLoadQueue;
}

function detectedAppLanguage(): string {
  try {
    if (typeof localStorage !== 'undefined') {
      const stored = localStorage.getItem('i18nextLng');
      if (stored) return stored.split('-')[0].toLowerCase();
    }
  } catch {
    /* ignore */
  }
  try {
    if (typeof navigator !== 'undefined' && navigator.language) {
      return navigator.language.split('-')[0].toLowerCase();
    }
  } catch {
    /* ignore */
  }
  return 'en';
}

i18n
  .use(LanguageDetector)
  .use(initReactI18next)
  .init({
    resources,
    fallbackLng: 'en',
    supportedLngs: ['en', 'hi', 'te', 'ta'],
    load: 'languageOnly',
    partialBundledLanguages: true,
    interpolation: { escapeValue: false },
    detection: {
      order: ['localStorage', 'navigator', 'htmlTag'],
      caches: ['localStorage'],
    },
    react: {
      useSuspense: false,
      bindI18n: 'languageChanged loaded',
      bindI18nStore: 'added removed',
    },
    saveMissing: true,
  });

// Prefetch preferred non-English locale without blocking first paint.
const preferred = detectedAppLanguage();
if (preferred !== 'en' && LOCALE_LOADERS[preferred]) {
  void ensureLocaleLoaded(preferred).then(() => {
    void i18n.changeLanguage(preferred);
  });
}

const originalChangeLanguage = i18n.changeLanguage.bind(i18n);
i18n.changeLanguage = (async (lng, ...rest) => {
  if (lng) await ensureLocaleLoaded(String(lng));
  return originalChangeLanguage(lng, ...rest);
}) as typeof i18n.changeLanguage;

